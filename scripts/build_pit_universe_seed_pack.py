def build_seed_pack() -> dict[str, object]:
    security_master: dict[str, dict[str, str]] = {}
    for snapshot in SNAPSHOTS:
        for item in snapshot["constituents"]:
            security_master[item["symbol"]] = {
                "symbol": item["symbol"],
                "company_name": item["company_name"],
            }

    return {
        "index_name": "NIFTY50",
        "description": (
            "Versioned point-in-time NIFTY50 universe seed pack built from official "
            "SEBI bulletin component tables plus the March 2020 NSE replacement notice."
        ),
        "symbol_isin_overrides": SYMBOL_ISIN_OVERRIDES,
        "security_master": [security_master[symbol] for symbol in sorted(security_master)],
        "snapshots": SNAPSHOTS,
    }


def main() -> None:
    seed_pack = build_seed_pack()
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(json.dumps(seed_pack, indent=2), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
